#!/usr/bin/env python3
"""
Extracts Arabic contextual forms from the font's own OpenType tables so the PS4 app can join Arabic letters
without a shaping engine: for every Arabic letter, the glyph ids of its isolated / initial / medial / final
forms (GSUB 'init', 'medi', 'fina' single substitutions) and the lam-alef ligatures (GSUB 'rlig').
Writes src/arabic_forms.h. Run again whenever the font changes.
"""
import sys
from fontTools.ttLib import TTFont

font = TTFont(sys.argv[1])
out = sys.argv[2]
gsub = font["GSUB"].table
order = font.getGlyphOrder()
gid = {name: i for i, name in enumerate(order)}
cmap = font.getBestCmap()


def lookups(tag):
    idx = set()
    for fr in gsub.FeatureList.FeatureRecord:
        if fr.FeatureTag == tag:
            idx.update(fr.Feature.LookupListIndex)
    return [gsub.LookupList.Lookup[i] for i in sorted(idx)]


def single_map(tag):
    m = {}
    for lk in lookups(tag):
        for st in lk.SubTable:
            if lk.LookupType == 7:
                st = st.ExtSubTable
            if hasattr(st, "mapping"):
                m.update(st.mapping)
    return m


init, medi, fina = single_map("init"), single_map("medi"), single_map("fina")
rows = []
for cp in sorted(cmap):
    if not (0x0620 <= cp <= 0x06FF):
        continue
    g = cmap[cp]
    if cp in range(0x064B, 0x0660) or cp == 0x0670:
        continue  # harakat: transparent marks
    i, m, f = init.get(g), medi.get(g), fina.get(g)
    join = 2 if (i or m) else (1 if f else 0)  # 2 dual-joining, 1 right-joining, 0 non-joining
    rows.append((cp, join, gid[g], gid[i] if i else 0, gid[m] if m else 0, gid[f] if f else 0))

# lam + alef ligatures (rlig); the ligature applies to the isolated and to the final lam forms
ligs = []
lam_iso = cmap.get(0x0644)
lam_fin = fina.get(lam_iso)
for lk in lookups("rlig"):
    for st in lk.SubTable:
        if lk.LookupType == 7:
            st = st.ExtSubTable
        if not hasattr(st, "ligatures"):
            continue
        for first, ligset in st.ligatures.items():
            for lig in ligset:
                if len(lig.Component) != 1:
                    continue
                comp = lig.Component[0]
                alef_cp = next((c for c, n in cmap.items() if n == comp or fina.get(n) == comp), None)
                if alef_cp is None:
                    continue
                kind = "iso" if first in (lam_iso, init.get(lam_iso)) else ("fin" if first in (lam_fin, medi.get(lam_iso)) else None)
                if kind:
                    ligs.append((alef_cp, kind, gid[lig.LigGlyph]))
lig_table = {}
for alef, kind, g in ligs:
    lig_table.setdefault(alef, {"iso": 0, "fin": 0})[kind] = g

with open(out, "w", encoding="utf-8") as h:
    h.write("/* Generated by tools/gen_arabic_forms.py from %s — do not edit. */\n" % sys.argv[1].split("/")[-1])
    h.write("typedef struct { unsigned short cp; unsigned char join; unsigned short isol, init, medi, fina; } ArabicForm;\n")
    h.write("static const ArabicForm ARABIC_FORMS[] = {\n")
    for r in rows:
        h.write("    {0x%04X, %d, %d, %d, %d, %d},\n" % r)
    h.write("};\n")
    h.write("typedef struct { unsigned short alef; unsigned short iso, fin; } LamAlef;\n")
    h.write("static const LamAlef LAM_ALEF[] = {\n")
    for alef in sorted(lig_table):
        h.write("    {0x%04X, %d, %d},\n" % (alef, lig_table[alef]["iso"], lig_table[alef]["fin"]))
    h.write("};\n")
print("%d letters, %d lam-alef ligatures -> %s" % (len(rows), len(lig_table), out))
